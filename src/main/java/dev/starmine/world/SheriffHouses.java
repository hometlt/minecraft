/**
 * The sheriff's house (owner 19.10): a large village (at least {@link #LARGE} beds round its bell, one middle-sized
 * village in {@link #MIDDLE_ODDS} with {@link #MIDDLE} beds) gets a house of stone bricks — mossy, cracked and cobbled in
 * places — with an iron door (stone pressure plates open it), iron trapdoors over its windows, a bed and a chest of
 * terran loot (grenades, gauss rounds, armor shards, now and then an armor piece or a stimpack), and its sheriff
 * ({@link Townsfolk.Role#SHERIFF}), who stays by it. Villages are generated by the game: the house is put up beside
 * one, on flat open ground facing its bell, once the village round the bell is loaded near a player (each bell is
 * looked at once, {@link Seen}).
 */
public final class SheriffHouses {
	public static final int LARGE = 10, MIDDLE = 6, MIDDLE_ODDS = 3;
	/** Bells within this of a player are looked at; the village is the beds within {@link #VILLAGE} of its bell. */
	static final int NEAR = 160, VILLAGE = 48;
	/** Half the house's side (7 x 7 outside), its height to the roof. */
	static final int HALF = 3, HEIGHT = 4;

	private SheriffHouses() {
	}

	public static void load() {
		ServerTickEvents.END_SERVER_TICK.register(server -> {
			if (server.getTickCount() % 100 != 37) return;
			ServerLevel level = server.overworld();
			for (ServerPlayer player : level.players()) look(level, player.blockPosition());
		});
	}

	/** The villages round `pos` not yet looked at: each gets its house (or not) once it is loaded. */
	static void look(ServerLevel level, BlockPos pos) {
		Seen seen = Seen.of(level);
		PoiManager poi = level.getPoiManager();
		for (BlockPos bell : poi.findAll(type -> type.is(PoiTypes.MEETING), at -> !seen.bells.contains(at.asLong()), pos, NEAR,
				PoiManager.Occupancy.ANY).toList()) {
			if (!level.hasChunksAt(bell.getX() - VILLAGE - 16, bell.getZ() - VILLAGE - 16, bell.getX() + VILLAGE + 16, bell.getZ() + VILLAGE + 16))
				continue; // not all of it is here yet
			seen.bells.add(bell.asLong());
			seen.setDirty();
			consider(level, bell, level.random);
		}
	}

	/** Whether this village gets a sheriff, and his house if so; the house's middle, or null. */
	public static @Nullable BlockPos consider(ServerLevel level, BlockPos bell, RandomSource random) {
		if (MapOverlay.covers(bell.getX(), bell.getZ())) return null; // a laid-over SC2 map has no villages of its own
		long beds = level.getPoiManager().getCountInRange(type -> type.is(PoiTypes.HOME), bell, VILLAGE, PoiManager.Occupancy.ANY);
		if (beds < LARGE && (beds < MIDDLE || random.nextInt(MIDDLE_ODDS) != 0)) return null;
		BlockPos site = site(level, bell, random);
		if (site == null) return null;
		build(level, site, facing(site, bell), random);
		return site;
	}

	/** Open ground beside the village, flat within 2 blocks, not on its paths and away from its buildings; its floor. */
	static @Nullable BlockPos site(ServerLevel level, BlockPos bell, RandomSource random) {
		int turn = random.nextInt(16);
		for (int r = 16; r <= VILLAGE; r += 3)
			for (int i = 0; i < 16; i++) {
				double angle = (i + turn) * Math.PI / 8;
				int x = bell.getX() + (int) Math.round(Math.cos(angle) * r), z = bell.getZ() + (int) Math.round(Math.sin(angle) * r);
				BlockPos floor = flat(level, x, z);
				if (floor != null) return floor;
			}
		return null;
	}

	/** The floor of a house at (x, z) if the ground there is fit for one, else null. */
	static @Nullable BlockPos flat(ServerLevel level, int x, int z) {
		int low = Integer.MAX_VALUE, high = Integer.MIN_VALUE;
		for (int dx = -HALF - 1; dx <= HALF + 1; dx++)
			for (int dz = -HALF - 1; dz <= HALF + 1; dz++) {
				int top = level.getHeight(Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, x + dx, z + dz);
				BlockPos ground = new BlockPos(x + dx, top - 1, z + dz);
				BlockState state = level.getBlockState(ground);
				if (!state.getFluidState().isEmpty() || !(state.is(BlockTags.DIRT) || state.is(BlockTags.SAND) || state.is(Blocks.GRAVEL)
						|| state.is(Blocks.SNOW_BLOCK) || state.is(BlockTags.BASE_STONE_OVERWORLD))) return null; // water, a path, a building
				low = Math.min(low, top);
				high = Math.max(high, top);
			}
		if (high - low > 2) return null;
		BlockPos floor = new BlockPos(x, high, z);
		// nothing of the village's in the way (a bed, a workstation, the bell)
		if (level.getPoiManager().getInRange(type -> true, floor, HALF + 3, PoiManager.Occupancy.ANY).findAny().isPresent()) return null;
		return floor;
	}

	/** The way from the house to the bell (the door faces it). */
	static Direction facing(BlockPos site, BlockPos bell) {
		int dx = bell.getX() - site.getX(), dz = bell.getZ() - site.getZ();
		return Math.abs(dx) > Math.abs(dz) ? (dx > 0 ? Direction.EAST : Direction.WEST) : (dz > 0 ? Direction.SOUTH : Direction.NORTH);
	}

	/** The house with its floor at `floor` and its door facing `door`, its chest filled, and its sheriff. */
	public static void build(ServerLevel level, BlockPos floor, Direction door, RandomSource random) {
		Rotation rotation = switch (door) { // the plan's door is on its south side
			case WEST -> Rotation.CLOCKWISE_90;
			case NORTH -> Rotation.CLOCKWISE_180;
			case EAST -> Rotation.COUNTERCLOCKWISE_90;
			default -> Rotation.NONE;
		};
		Plan plan = new Plan(level, floor, rotation);
		// ground: filled up to the floor, cleared above it
		for (int dx = -HALF - 1; dx <= HALF + 1; dx++)
			for (int dz = -HALF - 1; dz <= HALF + 1; dz++) {
				BlockPos column = plan.at(dx, -1, dz);
				for (int y = level.getHeight(Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, column.getX(), column.getZ()); y < floor.getY(); y++)
					level.setBlock(new BlockPos(column.getX(), y, column.getZ()), Blocks.DIRT.defaultBlockState(), Block.UPDATE_CLIENTS);
				for (int y = 0; y <= HEIGHT + 3; y++) plan.set(dx, y, dz, Blocks.AIR.defaultBlockState());
				boolean inside = Math.abs(dx) <= HALF && Math.abs(dz) <= HALF;
				plan.set(dx, -1, dz, !inside ? Blocks.GRASS_BLOCK.defaultBlockState()
					: Math.abs(dx) == HALF || Math.abs(dz) == HALF ? Blocks.STONE_BRICKS.defaultBlockState() : Blocks.POLISHED_ANDESITE.defaultBlockState());
			}
		// walls of stone bricks, here and there mossy, cracked or cobbled; corner pillars of chiselled bricks
		for (int dx = -HALF; dx <= HALF; dx++)
			for (int dz = -HALF; dz <= HALF; dz++) {
				if (Math.abs(dx) != HALF && Math.abs(dz) != HALF) continue;
				boolean corner = Math.abs(dx) == HALF && Math.abs(dz) == HALF;
				for (int y = 0; y < HEIGHT; y++) plan.set(dx, y, dz, corner ? Blocks.CHISELED_STONE_BRICKS.defaultBlockState() : wall(random));
				plan.set(dx, HEIGHT + 1, dz, corner || (dx + dz & 1) == 0 ? Blocks.STONE_BRICK_SLAB.defaultBlockState() : Blocks.AIR.defaultBlockState());
			}
		// the roof
		for (int dx = -HALF; dx <= HALF; dx++)
			for (int dz = -HALF; dz <= HALF; dz++) plan.set(dx, HEIGHT, dz, Blocks.STONE_BRICKS.defaultBlockState());
		// the iron door, opened by stone pressure plates on both sides
		plan.set(0, 0, HALF, Blocks.IRON_DOOR.defaultBlockState().setValue(DoorBlock.FACING, Direction.NORTH)
			.setValue(DoorBlock.HINGE, DoorHingeSide.LEFT).setValue(DoorBlock.HALF, DoubleBlockHalf.LOWER));
		plan.set(0, 1, HALF, Blocks.IRON_DOOR.defaultBlockState().setValue(DoorBlock.FACING, Direction.NORTH)
			.setValue(DoorBlock.HINGE, DoorHingeSide.LEFT).setValue(DoorBlock.HALF, DoubleBlockHalf.UPPER));
		plan.set(0, 0, HALF + 1, Blocks.STONE_PRESSURE_PLATE.defaultBlockState());
		plan.set(0, 0, HALF - 1, Blocks.STONE_PRESSURE_PLATE.defaultBlockState());
		// windows two blocks high, shut with iron trapdoors
		for (int[] w : new int[][] {{-HALF, -1}, {-HALF, 1}, {HALF, -1}, {HALF, 1}, {-1, -HALF}, {1, -HALF}, {2, HALF}}) {
			Direction out = Math.abs(w[0]) == HALF ? (w[0] > 0 ? Direction.EAST : Direction.WEST) : (w[1] > 0 ? Direction.SOUTH : Direction.NORTH);
			for (int y = 1; y <= 2; y++)
				plan.set(w[0], y, w[1], Blocks.IRON_TRAPDOOR.defaultBlockState().setValue(TrapDoorBlock.FACING, out).setValue(TrapDoorBlock.OPEN, true)
					.setValue(TrapDoorBlock.HALF, Half.BOTTOM));
		}
		// inside: a bed, the chest, a crafting table, a lantern
		plan.set(2, 0, -1, Blocks.RED_BED.defaultBlockState().setValue(BedBlock.FACING, Direction.NORTH).setValue(BedBlock.PART, BedPart.FOOT));
		plan.set(2, 0, -2, Blocks.RED_BED.defaultBlockState().setValue(BedBlock.FACING, Direction.NORTH).setValue(BedBlock.PART, BedPart.HEAD));
		plan.set(-2, 0, -2, Blocks.CHEST.defaultBlockState().setValue(ChestBlock.FACING, Direction.SOUTH));
		plan.set(-2, 0, 0, Blocks.CRAFTING_TABLE.defaultBlockState());
		plan.set(0, HEIGHT - 1, 0, Blocks.LANTERN.defaultBlockState().setValue(LanternBlock.HANGING, true));
		if (level.getBlockEntity(plan.at(-2, 0, -2)) instanceof ChestBlockEntity chest) fill(chest, random);
		// the sheriff
		Townsfolk sheriff = Guns.SHERIFF.create(level);
		if (sheriff != null) {
			BlockPos at = plan.at(0, 0, 0);
			sheriff.moveTo(at.getX() + 0.5, at.getY(), at.getZ() + 0.5, random.nextFloat() * 360, 0);
			sheriff.keepHome(floor);
			level.addFreshEntity(sheriff);
		}
	}

	/** A block of the wall: mostly stone bricks. */
	private static BlockState wall(RandomSource random) {
		int roll = random.nextInt(20);
		return (roll < 12 ? Blocks.STONE_BRICKS : roll < 15 ? Blocks.CRACKED_STONE_BRICKS : roll < 17 ? Blocks.MOSSY_STONE_BRICKS
			: roll < 19 ? Blocks.COBBLESTONE : Blocks.ANDESITE).defaultBlockState();
	}

	/** The sheriff's chest: grenades and gauss rounds always, then a few terran things by chance. */
	static void fill(ChestBlockEntity chest, RandomSource random) {
		java.util.List<ItemStack> loot = new java.util.ArrayList<>();
		loot.add(new ItemStack(Guns.PUNISHER_GRENADE, 4 + random.nextInt(9)));
		loot.add(new ItemStack(Guns.GAUSS_AMMO, 16 + random.nextInt(33)));
		if (random.nextFloat() < 0.5f) loot.add(new ItemStack(Guns.KD8_CHARGE, 2 + random.nextInt(5)));
		if (random.nextFloat() < 0.3f) loot.add(new ItemStack(Guns.CANISTER_ROUND, 4 + random.nextInt(5)));
		if (random.nextFloat() < 0.6f) loot.add(new ItemStack(dev.starmine.suit.SuitItems.SHARDS.get(UnitKind.Race.TERRAN), 1 + random.nextInt(4)));
		if (random.nextFloat() < 0.35f)
			loot.add(new ItemStack(dev.starmine.suit.SuitItems.piece(UnitKind.Race.TERRAN, dev.starmine.suit.SuitItems.TYPES.get(random.nextInt(4)))));
		if (random.nextFloat() < 0.25f) loot.add(new ItemStack(dev.starmine.possess.ModuleItem.of(dev.starmine.ability.Ability.STIMPACK)));
		if (random.nextFloat() < 0.5f) loot.add(new ItemStack(dev.starmine.mineral.Minerals.SHARD, 4 + random.nextInt(9)));
		if (random.nextFloat() < 0.1f) loot.add(new ItemStack(Guns.GAUSS_RIFLE));
		java.util.List<Integer> slots = new java.util.ArrayList<>();
		for (int i = 0; i < chest.getContainerSize(); i++) slots.add(i);
		net.minecraft.Util.shuffle(slots, random);
		for (int i = 0; i < loot.size(); i++) chest.setItem(slots.get(i), loot.get(i));
	}

	/** The house's plan in its own frame (door on the south): places blocks turned to the real door's side. */
	private record Plan(ServerLevel level, BlockPos floor, Rotation rotation) {
		BlockPos at(int dx, int dy, int dz) {
			return floor.offset(new BlockPos(dx, dy, dz).rotate(rotation));
		}

		void set(int dx, int dy, int dz, BlockState state) {
			level.setBlock(at(dx, dy, dz), state.rotate(rotation), Block.UPDATE_CLIENTS);
		}
	}

	/** The bells already looked at, per level. */
	static final class Seen extends SavedData {
		private static final Factory<Seen> FACTORY = new Factory<>(Seen::new, Seen::load, null);
		final LongSet bells = new LongOpenHashSet();

		static Seen of(Level level) {
			return ((ServerLevel) level).getDataStorage().computeIfAbsent(FACTORY, "starmine_sheriff_houses");
		}

		@Override
		public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
			tag.putLongArray("bells", bells.toLongArray());
			return tag;
		}

		private static Seen load(CompoundTag tag, HolderLookup.Provider registries) {
			Seen seen = new Seen();
			for (long bell : tag.getLongArray("bells")) seen.bells.add(bell);
			return seen;
		}
	}
}
